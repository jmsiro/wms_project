    create table rates
    (
        id                                 int auto_increment            primary key,
        account_id                         int                           null,
        shipment_type                      enum('NATIONAL', 'INTERNATIONAL')  not null,
        price                              decimal(4, 2)                 not null,
        created_at                         datetime                      not null,
        updated_at                         datetime                      null
    )
        charset = utf8mb3;

